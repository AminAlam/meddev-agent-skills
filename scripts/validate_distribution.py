#!/usr/bin/env python3
"""Validate portable skills, native manifests, links, and the generated catalog."""
import argparse
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-catalog', action='store_true')
    args = parser.parse_args()
    errors, records, ids = [], [], set()

    def check(condition, message):
        if not condition:
            errors.append(message)

    paths = sorted((ROOT / 'skills').glob('*/SKILL.md'))
    check(bool(paths), 'No skills found')
    for path in paths:
        relative = path.relative_to(ROOT)
        try:
            text = path.read_text()
            check(text.startswith('---\n'), f'{relative}: missing frontmatter')
            data = yaml.safe_load(text.split('---', 2)[1])
            name, description, meta = data['name'], data['description'], data['metadata']
            check(name == path.parent.name, f'{relative}: name differs from directory')
            check(bool(re.fullmatch(r'meddev-[a-z0-9]+(?:-[a-z0-9]+)*', name)) and len(name) <= 64,
                  f'{relative}: invalid skill name')
            check(isinstance(description, str) and 0 < len(description) <= 1024,
                  f'{relative}: description must contain 1–1024 characters')
            check(set(data) <= {'name', 'description', 'license', 'metadata', 'compatibility', 'allowed-tools'},
                  f'{relative}: unsupported top-level metadata')
            check(all(isinstance(v, str) for v in meta.values()), f'{relative}: metadata must contain strings')
            for key in ('skill_id', 'version', 'last_updated', 'applies_to', 'jurisdiction', 'prerequisites', 'category'):
                check(key in meta, f'{relative}: missing metadata.{key}')
            check(meta['skill_id'] not in ids, f'{relative}: duplicate skill_id')
            ids.add(meta['skill_id'])
            records.append((relative, data))
        except (KeyError, IndexError, TypeError, yaml.YAMLError) as exc:
            errors.append(f'{relative}: invalid metadata: {exc}')

    for path, data in records:
        for prerequisite in filter(None, map(str.strip, data['metadata']['prerequisites'].split(','))):
            check(prerequisite in ids, f'{path}: unknown prerequisite {prerequisite}')

    manifests = ['plugin.json', '.claude-plugin/plugin.json', '.cursor-plugin/plugin.json']
    base = json.loads((ROOT / manifests[0]).read_text())
    for filename in manifests:
        manifest = json.loads((ROOT / filename).read_text())
        for key in ('name', 'version', 'description', 'license'):
            check(manifest.get(key) == base.get(key), f'{filename}: inconsistent {key}')
    check(bool(re.fullmatch(r'\d+\.\d+\.\d+', base['version'])), 'Invalid plugin version')
    for filename in ('.claude-plugin/marketplace.json', '.cursor-plugin/marketplace.json', '.agents/plugins/marketplace.json'):
        market = json.loads((ROOT / filename).read_text())
        check(market['name'] == base['name'], f'{filename}: unexpected marketplace name')
        check(len(market['plugins']) == 1, f'{filename}: expected one collection')
        entry = market['plugins'][0]
        check(entry['name'] == base['name'], f'{filename}: plugin name mismatch')
        source = entry['source']
        source = source['path'] if isinstance(source, dict) else source
        check(source == './' and (ROOT / source / 'skills').is_dir(), f'{filename}: incorrect plugin root')

    for path in ROOT.rglob('*.md'):
        if '.git' in path.parts:
            continue
        for target in re.findall(r'\]\(([^\s)]+)\)', path.read_text()):
            if re.match(r'[a-z]+:', target) or target.startswith('#'):
                continue
            target = target.split('#')[0]
            if args.write_catalog and (path.parent / target).resolve() == ROOT / 'SKILLS.md':
                continue
            check((path.parent / target).exists(), f'{path.relative_to(ROOT)}: missing link {target}')

    catalog = '# Skill catalog\n\nGenerated by `python3 scripts/validate_distribution.py --write-catalog`.\n\n'
    catalog += 'Use this mapping to select skills and resolve prerequisite IDs. Metadata prerequisites are not automatically installed by native tools.\n\n'
    catalog += '| Skill ID | Installable skill | Category | Prerequisites |\n|---|---|---|---|\n'
    for path, data in records:
        meta = data['metadata']
        catalog += f"| {meta['skill_id']} | [{data['name']}]({path.as_posix()}) | {meta['category']} | {meta['prerequisites'] or '—'} |\n"
    catalog_path = ROOT / 'SKILLS.md'
    if args.write_catalog:
        catalog_path.write_text(catalog)
    else:
        check(catalog_path.exists() and catalog_path.read_text() == catalog,
              'SKILLS.md is stale; run with --write-catalog')
    if errors:
        raise SystemExit('\n'.join(errors))
    print(f'Validated {len(records)} skills, 3 plugin manifests, 3 marketplaces, and local Markdown links.')


if __name__ == '__main__':
    main()
